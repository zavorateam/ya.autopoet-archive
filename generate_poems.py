def get_existing_numbers(directory: str) -> set:
    """
    Возвращает множество уже занятых номеров файлов в формате N.txt в указанной директории.
    """
    pattern = re.compile(r'^(\d+)\.txt$')
    used = set()
    for fname in os.listdir(directory):
        match = pattern.match(fname)
        if match:
            used.add(int(match.group(1)))
    return used


def save_poems(poems_list):
    """
    Сохраняет каждое стихотворение из списка в отдельный файл с порядковым номером,
    пропуская уже занятые номера.
    """
    cwd = os.getcwd()
    used_nums = get_existing_numbers(cwd)
    next_num = 1

    for poem in poems_list:
        # Найти первый свободный номер
        while next_num in used_nums:
            next_num += 1
        filename = f"{next_num}"
        with open(filename, 'w', encoding='utf-8') as f:
            # Записываем стихотворение без изменений форматирования
            f.write(poem.strip() + '\n')
        print(f"Сохранено стихотворение под именем: {filename}")
        used_nums.add(next_num)
        next_num += 1


